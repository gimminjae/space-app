import {scrypt,randomBytes} from 'node:crypto';
import {promisify} from 'node:util';
import {createInterface} from 'node:readline/promises';
const rl=createInterface({input:process.stdin,output:process.stdout});
const value=await rl.question('새 관리 비밀번호 (12자 이상): '); rl.close();
if(value.length<12) throw new Error('12자 이상으로 설정해 주세요.');
const salt=randomBytes(32).toString('hex');
const hash=await promisify(scrypt)(value,salt,64);
console.log('ADMIN_PASSWORD_HASH=scrypt:'+salt+':'+hash.toString('hex'));
console.log('ADMIN_SESSION_SECRET='+randomBytes(48).toString('base64url'));
